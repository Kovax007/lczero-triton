"""The one place that decides what an lab artifact's buffers are called.

`UploadWeights` matches an artifact's buffers to a carrier's initializers **by
name**, and nothing checks that the two sides were generated by the same idea of
what a name is. A mismatch is not a numerical error -- it is a hard failure at
load, or worse, a silent one if two different tensors happen to agree on shape.

So the graph builder and the weight generator both read their names from here,
and neither is allowed a literal of its own. The plan for each tensor also
carries the shape and data type the buffer will declare, which is what lets the
generator produce an initializer that satisfies `ValidateInitializer` without
the builder having to be consulted.
"""

